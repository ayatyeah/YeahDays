import { mkdirSync } from 'node:fs';
import { test, check, newUser, session, openSection } from '../harness.mjs';

test('Реальный квиз ПМ: варианты, разборы, конспекты и сохранение', async () => {
  const user = await newUser();
  const { page, browser, errors } = await session({ user, engine: 'chromium', serviceWorkers: 'block', initScript: "localStorage.setItem('yd-install-dismissed','1')" });
  const root = page.getByTestId('pm-real-quiz');
  try {
    await openSection(page, '/events/project-management-quiz-2-real');
    await root.waitFor();
    const question = page.getByTestId('pm-real-question');
    const controls = page.getByTestId('pm-quiz-controls');
    const scroller = page.getByTestId('pm-quiz-scroll');
    const filters = page.getByTestId('pm-quiz-filters');
    await question.getByRole('radio').first().waitFor();
    check(await question.getByRole('radio').count() === 5, 'оригинальные A–E');
    check(await page.getByTestId('pm-real-alternatives').count() === 0, 'подсказки скрыты до проверки');
    check(!(await filters.evaluate(el => el.open)), 'фильтры изначально свёрнуты');
    mkdirSync('artifacts/pm-real-quiz', { recursive:true });
    for (const [width,height] of [[320,568],[390,844],[1366,768]]) {
      await page.setViewportSize({ width,height });
      await scroller.evaluate(el => { el.scrollTop = 0; });
      const first = await question.getByRole('radio').first().boundingBox();
      const bar = await controls.boundingBox();
      check(first.y < height - 80, `ответы видны сразу ${width}`);
      check(bar.y >= 0 && bar.y + bar.height <= height + 1, `действия внутри экрана ${width}`);
      check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `нет горизонтального переполнения ${width}`);
      await scroller.evaluate(el => { el.scrollTop = el.scrollHeight; });
      const after = await controls.boundingBox();
      check(Math.abs(bar.y - after.y) < 1, `панель не уезжает при прокрутке ${width}`);
      await scroller.evaluate(el => { el.scrollTop = 0; });
      await page.screenshot({ path:`artifacts/pm-real-quiz/compact-${width}.png` });
    }
    const prompt = await question.locator('#pm-question-text').boundingBox();
    const options = await question.getByRole('radiogroup').boundingBox();
    check(options.x > prompt.x + prompt.width, 'на ноутбуке условие и ответы рядом');
    await question.getByRole('radio').nth(2).check();
    await controls.getByRole('button', { name:'Проверить ответ', exact:true }).click();
    check((await controls.innerText()).includes('Правильный ответ: A'), 'результат доступен в постоянной панели');
    check(!(await page.getByTestId('pm-real-explanation').evaluate(el => el.open)), 'разбор не удлиняет экран автоматически');
    await page.reload();
    await question.getByRole('radio').first().waitFor();
    check(await question.getByRole('radio').nth(2).isChecked(), 'ответ сохранён');
    await controls.getByRole('button', { name:'Следующий →', exact:true }).click();
    check((await question.innerText()).includes('№2'), 'следующий вопрос без прокрутки к кнопке');
    check(await scroller.evaluate(el => el.scrollTop) === 0, 'новый вопрос начинается сверху');
    await filters.locator(':scope > summary').click();
    await root.getByLabel('Вариант теста', { exact:true }).selectOption('4');
    check((await filters.innerText()).includes('Отсутствуют №28'), 'пропуски сохранены');
    await root.getByLabel('Вариант теста', { exact:true }).selectOption('unknown');
    check((await filters.innerText()).includes('Вопросов по фильтрам: 23'), 'неизвестный вариант отдельно');
    await root.getByLabel('Вариант теста', { exact:true }).selectOption('3');
    check((await filters.innerText()).includes('Вопросов по фильтрам: 36'), 'новый набор без нечитаемых заданий');
    check((await question.innerText()).includes('technical excellence'), 'новый вопрос из фото');
    await page.reload({ waitUntil: 'networkidle' });
    await question.getByRole('radio').first().waitFor();
    check((await question.innerText()).includes('technical excellence'), 'вариант 3 сохраняется после перезагрузки');
    await filters.locator(':scope > summary').click();
    await root.getByLabel('Вариант теста', { exact:true }).selectOption('5');
    check((await filters.innerText()).includes('Вопросов по фильтрам: 46'), 'вариант 5 сохранён');
    await root.getByRole('button', { name:'Краткий конспект', exact:true }).click();
    check(await root.locator('section[id^="note-"]').count() === 15, 'все темы конспекта');
    await root.getByRole('button', { name:'Развёрнутый конспект', exact:true }).click();
    await root.locator('#note-evm').getByRole('button', { name:'В1 · №18 →', exact:true }).click();
    await question.getByRole('button', { name:'Показать разбор без ответа', exact:true }).click();
    const alternativeSection = page.getByTestId('pm-real-alternatives');
    await alternativeSection.locator(':scope > summary').click();
    const alternatives = page.getByTestId('pm-real-alternative');
    check(await alternatives.count() === 4, 'четыре альтернативы доступны');
    await alternatives.nth(0).locator('summary').click();
    await alternatives.nth(1).locator('summary').click();
    check(!(await alternatives.nth(0).evaluate(el => el.open)), 'открыта только одна переформулировка');
    check((await alternatives.nth(1).innerText()).includes('Почему C'), 'пояснение соответствует букве');
    await page.setViewportSize({ width:390,height:844 });
    await page.screenshot({ path:'artifacts/pm-real-quiz/compact-explanation.png' });
    await controls.getByRole('button', { name:'Следующий →', exact:true }).click();
    check(await page.getByTestId('pm-real-alternatives').count() === 0, 'подсказки не переходят к следующему вопросу');
    await root.getByRole('button', { name:'Источники', exact:true }).click();
    check(await root.locator('details').count() === 83, 'все источники доступны');
    check(await page.evaluate(() => document.body.style.overflow !== 'hidden'), 'обычная прокрутка восстановлена вне тренировки');
    check(!errors.some(e => /hydration|Minified React error|Uncaught/i.test(e)), 'нет ошибок React');
  } finally { await browser.close(); }
});
