"use client";

/**
 * Обёртка страниц вне оболочки приложения (/settings, /manage, витрина).
 *
 * Здесь был направленный въезд экрана: слева или справа, в зависимости от
 * того, куда идёшь. Убрано вместе с анимацией разделов — между нажатием и
 * готовой страницей стояла ощутимая пауза, а резкая смена читается как
 * отзывчивость.
 *
 * Компонент оставлен, а не удалён из Shell: он держит каркас (min-height),
 * пока новая страница монтируется, — без этого навигация подпрыгивает на
 * кадр на коротких страницах.
 */
export default function PageTransition({ children }: { children: React.ReactNode }) {
  return <div className="flex min-h-[60vh] flex-1 flex-col">{children}</div>;
}
